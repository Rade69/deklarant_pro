def add(a: float, b: float) -> float:
    """
    Return the sum of two numbers.

    Parameters
    ----------
    a : float
        First number.
    b : float
        Second number.

    Returns
    -------
    float
        The sum of a and b.

    Examples
    --------
    >>> add(2, 3)
    5.0
    >>> add(-1, 1)
    0.0
    """
    return a + b
